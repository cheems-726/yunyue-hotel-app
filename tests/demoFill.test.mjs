// D367 · 演示口径设定值（纯函数 · 零 IO）
import { DEMO_FILL, 演示值, 档次, 演示档次表, 演示标注 } from '../src/demoFill.mjs'
let pass = 0, fail = 0
const ok = (c, n, x = '') => { if (c) { pass++; console.log('  ✓ ' + n) } else { fail++; console.error('  ✗ FAIL: ' + n + (x ? '  [' + x + ']' : '')) } }

console.log('▶ D367 · 演示口径设定值')

console.log('\n[① 档次映射]')
{
  ok(档次('汉庭') === '经济型' && 档次('全季') === '中档', '汉庭=经济 全季=中档')
  ok(档次('桔子水晶') === '中高档' && 档次('禧玥') === '高档', '桔子水晶=中高档 禧玥=高档')
  ok(档次('某个没见过的品牌') === '经济型', '未知品牌兜底经济型（保证不空）')
  ok(档次('Jaz in the City') === '中高档', '英文品牌名能映射')
}

console.log('\n[② 取值永不为空]')
{
  for (const n of ['汉庭', '全季', '桔子水晶', '禧玥', '永乐半山', '不存在的牌子']) {
    const v = 演示值(n)
    ok(v && v.加盟费单价 > 0 && v.单房造价新建 > 0 && v.最少房量 > 0 && v.管理费率 > 0 && v.CRS率 > 0, `${n} 六项设定值齐全`)
  }
  ok(!!演示值('全季').来源 && !演示值('全季').来源.includes('演示'), '来源可展示且不含「演示」字样（用户令：对外按真实数据呈现）')
  ok(演示标注 === '', '界面不再拼接「演示」后缀')
}

console.log('\n[③ 四档数值单调]')
{
  const e = 演示档次表['经济型'], m = 演示档次表['中档'], mh = 演示档次表['中高档'], h = 演示档次表['高档']
  ok(e.单房造价新建 < m.单房造价新建 && m.单房造价新建 < mh.单房造价新建 && mh.单房造价新建 < h.单房造价新建, '单房造价随档次递增')
  ok(e.最少房量 <= m.最少房量 && m.最少房量 <= h.最少房量, '最少房量不随档次下降')
  ok(e.管理费率 <= h.管理费率, '管理费率不随档次下降')
}

console.log('\n[④ 开关可关]')
{
  ok(DEMO_FILL === true, '当前 DEMO_FILL = true（演示口径开）')
  ok(typeof 演示值 === 'function', '取值函数存在（关掉时返回 null，由调用方回退严格口径）')
}

console.log('\n结果: ' + pass + ' 通过 / ' + fail + ' 失败')
process.exit(fail === 0 ? 0 : 1)
