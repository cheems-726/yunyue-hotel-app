// V131 §1-A · 押注评分（阈值刀口 · 方向四档 · 周锁定 · 台账校准）
// 运行：node tests/bets.test.mjs   （挂 run-all fast）
import { 净利档Of, 出租率得分, 方向得分, 判押注, 押注有效, 押注校准, 押注满分 } from '../src/bets.mjs'

let pass = 0, fail = 0
const ok = (c, n, extra = '') => { if (c) { pass++; console.log('  ✓ ' + n) } else { fail++; console.error('  ✗ FAIL: ' + n + (extra ? '  [' + extra + ']' : '')) } }

console.log('▶ V131 §1-A · 押注评分')

console.log('\n[①] 出租率误差刀口（≤3→10 · ≤6→7 · ≤10→5 · ≤15→2 · 其余0）')
{
  const 例 = [[70, 70, 10], [67, 70, 10], [73, 70, 10], [66, 70, 7], [64, 70, 7], [63, 70, 5], [60, 70, 5], [59, 70, 2], [55, 70, 2], [54, 70, 0], [0, 100, 0]]
  const 坏 = 例.filter(([p, a, s]) => 出租率得分(p, a) !== s)
  ok(坏.length === 0, `11 个刀口样本全部命中（错 ${坏.length}）`, JSON.stringify(坏))
  ok(出租率得分(70, 70) === 10 && 出租率得分(70, 54) === 0, '两端（0 误差满分 / 16 误差 0 分）')
}

console.log('\n[②] 净利四档与方向得分（中5 · 差一档2 · 差两档0）')
{
  ok(净利档Of(-60000) === '明显亏损', '-6 万 ⇒ 明显亏损')
  ok(净利档Of(-1) === '小幅亏损' && 净利档Of(0) === '小幅盈利', '-1 ⇒ 小幅亏损；0 ⇒ 小幅盈利（0 归盈利侧）')
  ok(净利档Of(50000) === '小幅盈利' && 净利档Of(50001) === '明显盈利', '5 万边界：≤5 万小幅 / >5 万明显')
  ok(方向得分('小幅亏损', -30000) === 5, '押中 ⇒ 5')
  ok(方向得分('小幅盈利', -30000) === 2, '差一档 ⇒ 2')
  ok(方向得分('明显盈利', -30000) === 0, '差两档以上 ⇒ 0')
  ok(方向得分('乱填', -30000) === 0, '未知方向 ⇒ 0（不静默给分）')
}

console.log('\n[③] 判押注：总分 = 出租率 + 方向（满分 15）')
{
  const r = 判押注({ week: 3, 出租率: 68, 净利方向: '小幅亏损' }, { occupancy: 70, netProfit: -30000 })
  ok(r.出租率得分 === 10 && r.方向得分 === 5 && r.总分 === 15, `68 vs 70 / 小幅亏损 ⇒ 15 分（实得 ${r.总分}）`)
  ok(r.实际方向 === '小幅亏损' && r.误差 === 2, '回填实际方向/误差')
  ok(押注满分 === 15, '满分常量 = 15')
  const 旧档 = 判押注({ week: 3, 出租率: 50, 净利方向: '明显盈利' }, { occupancy: 70, profit: -300000 })
  ok(旧档.总分 === 0, '旧档只有 profit 也能打分（netProfit 缺省回退）')
}

console.log('\n[④] 周锁定：week 必须等于本周 · 0–100 整数 · 四档内')
{
  ok(押注有效({ week: 3, 出租率: 70, 净利方向: '小幅盈利' }, 3) === true, '合法押注 ⇒ true')
  ok(押注有效({ week: 2, 出租率: 70, 净利方向: '小幅盈利' }, 3) === false, '上周押注 ⇒ false（周锁定）')
  ok(押注有效({ week: 3, 出租率: 70.5, 净利方向: '小幅盈利' }, 3) === false, '非整数 ⇒ false')
  ok(押注有效({ week: 3, 出租率: 101, 净利方向: '小幅盈利' }, 3) === false, '越界 ⇒ false')
  ok(押注有效({ week: 3, 出租率: 70, 净利方向: '乱填' }, 3) === false, '方向不在四档 ⇒ false')
  ok(押注有效(null, 3) === false, '空押注 ⇒ false（未押注）')
}

console.log('\n[⑤] 台账第五列：按周取校准分；没结算 ⇒ null（显 —）')
{
  const 史 = [{ week: 1, 总分: 12 }, { week: 2, 总分: 4 }]
  ok(押注校准(史, 2) === 4, '第 2 周 ⇒ 4')
  ok(押注校准(史, 3) === null, '第 3 周未结算 ⇒ null')
  ok(押注校准([], 1) === null && 押注校准(null, 1) === null, '空历史 ⇒ null')
}

console.log('\n结果: ' + pass + ' 通过 / ' + fail + ' 失败')
process.exit(fail === 0 ? 0 : 1)
