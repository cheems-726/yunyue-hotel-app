# -*- coding: utf-8 -*-
import io, sys
def patch(path, subs):
    s = io.open(path, encoding='utf-8', newline='').read()
    for a, b in subs:
        if a not in s:
            print('MISS %s :: %s' % (path, a[:70])); sys.exit(1)
        s = s.replace(a, b, 1)
    io.open(path, 'w', encoding='utf-8', newline='').write(s)
    print('OK %s (%d 处)' % (path, len(subs)))

