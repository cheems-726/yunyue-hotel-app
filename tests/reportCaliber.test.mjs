//
// ── 反向验证（R3）─────────────────────────────────────────────
//   删掉任一现行报告的「口径版本」行 / 把"含"改成"不含" ⇒ 本套件必红；还原 ⇒ 绿。
//   （历史报告：删掉「历史快照」标记 ⇒ 红。）
//
// 运行：node tests/reportCaliber.test.mjs   （挂 run-all fast）
