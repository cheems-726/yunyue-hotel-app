// ① 死条目自检：文件在 + 真落在扫描范围内
console.log('▶ §15.1-C 产物报告口径版本守门')
console.log(`  引擎现状（源码单源）：${引擎口径}加盟两费（已接入品牌 ${已接入品牌.length} 个 · NET_DEF ${NET_DEF.includes('加盟两费') ? '含' : '不含'}该项）\n`)
console.log('[1] 台账死条目自检（文件在 · 真在范围内 · 类型合法）')
{
  const 缺文件 = 台账.filter(e => !existsSync(path.join(DIR, e.f))).map(e => e.f)
  ok(缺文件.length === 0, `台账 ${台账.length} 条全部存在`, 缺文件.join(', '))
  const 类型集 = new Set(台账.map(e => e.类型))
  const 非法类型 = [...类型集].filter(t => !['现行', '历史', '豁免'].includes(t))
  ok(非法类型.length === 0, '类型只用 现行/历史/豁免 三种', 非法类型.join(','))
  const 重复 = 台账.map(e => e.f).filter((f, i, a) => a.indexOf(f) !== i)
  ok(重复.length === 0, '台账无重复条目', 重复.join(','))
  const 无理由 = 台账.filter(e => !e.why || e.why.length < 6).map(e => e.f)
  ok(无理由.length === 0, '每条都写了 why（不许只登记不给理由）', 无理由.join(','))
}

// ② 现行报告：口径版本行 且 声明值 === 引擎现状
console.log('\n[2] 现行报告：口径版本行 === 引擎现状')
{
  const 现行 = 台账.filter(e => e.类型 === '现行')
  ok(现行.length > 0, `台账里有 ${现行.length} 份"现行"报告`)
  for (const e of 现行) {
    const t = rd(path.join(DIR, e.f))
    const m = t && /口径版本\*\*：\s*\**\s*(含|不含)/.exec(t)
    ok(!!m, `${e.f}：含机器可读「口径版本：含/不含」行`, m ? '' : '未找到形如「> **口径版本**：**含加盟两费（…）**」的行')
    if (m) ok(m[1] === 引擎口径, `${e.f}：声明「${m[1]}加盟两费」=== 引擎现状「${引擎口径}」`, `声明=${m[1]} 引擎=${引擎口径} ⇒ 改引擎口径后必须同步改本报告`)
  }
  // 反例自检：判据必须能区分"含"与"不含"（不然就是浅层校验）
  const 样本含 = '> **口径版本**：**含加盟两费（§14.3 起）**'
  const 样本不含 = '> **口径版本**：**不含加盟两费**'
  ok(/口径版本\*\*：\s*\**\s*(含|不含)/.exec(样本含)?.[1] === '含' && /口径版本\*\*：\s*\**\s*(含|不含)/.exec(样本不含)?.[1] === '不含',
    '判据自检：能区分「含」与「不含」（非浅层 contains 校验）')
}

// ③ 历史报告：首部须有「历史快照」+ 指向现行
console.log('\n[3] 历史报告：首部标「历史快照」+ 指向现行报告')
{
  const 历史 = 台账.filter(e => e.类型 === '历史')
  const 缺标 = [], 缺指向 = []
  for (const e of 历史) {
    const 头 = (rd(path.join(DIR, e.f)) || '').slice(0, 1600)
    if (!头.includes('历史快照')) 缺标.push(e.f)
    if (!/现行数字见|现行口径见|现行报告/.test(头)) 缺指向.push(e.f)
  }
  ok(缺标.length === 0, `历史报告 ${历史.length} 份首部均标「历史快照」`, 缺标.join(', '))
  ok(缺指向.length === 0, '历史报告均指向现行报告（不许让人拿旧数字当现在的读）', 缺指向.join(', '))
  ok(历史.length > 0, `台账里有 ${历史.length} 份"历史"报告（分类不是空的）`)
}

// ④ 覆盖度：含引擎数值签名的 .md 必须已登记
console.log('\n[4] 覆盖度断言：含"引擎数值签名"的报告必须出现在台账')
{
  // 签名 = 千分位金额（引擎直出，如 1,490,000 / 2,191,060）；另按文件名兜底（长跑/二期报告）
  const 签名 = /(?<![\d.])\d{1,3}(?:,\d{3})+(?![\d])/
  const 文件名兜底 = /长跑报告|二期报告/
  const 全部 = readdirSync(DIR).filter(f => f.endsWith('.md'))
  const 在范围内 = 全部.filter(f => {
    if (文件名兜底.test(f)) return true
    return 签名.test(rd(path.join(DIR, f)) || '')
  })
  const 已登记 = new Set(台账.map(e => e.f))
  const 漏登 = 在范围内.filter(f => !已登记.has(f))
  ok(漏登.length === 0, `范围内 ${在范围内.length} 份 / 目录 ${全部.length} 份 .md 全部已登记`, 漏登.join(', '))
  if (漏登.length) console.log('     ⇒ 新报告须登记进台账（现行/历史/豁免 三选一，并写 why），不许绕过')
  // 判据自检：签名不能把普通中文报告全扫进来，也不能一条都不扫（两边都验）
  ok(签名.test('期末资金 2,191,060 元'), '判据自检：千分位金额命中')
  ok(!签名.test('第 15 行 · 40.4% · 18 周'), '判据自检：无千分位的普通文字不误报')
  ok(在范围内.length >= 3, `范围内份数 ${在范围内.length} ≥ 3（判据没有退化成"什么都扫不到"）`)
  // 死条目：登记为 现行/历史 却不在范围内 ⇒ 条目腐烂（签名消失或文件被搬走）
  const 不在范围 = 台账.filter(e => e.类型 !== '豁免' && !在范围内.includes(e.f)).map(e => e.f)
  ok(不在范围.length === 0, '登记为 现行/历史 的条目都真的在扫描范围内（条目不腐烂）', 不在范围.join(', '))
}

