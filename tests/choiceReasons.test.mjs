// V113-1.3 判据：每步取舍句（字数下限 + 缺项点名）+ 终局宣言（带时间戳 · 一次生成不可编辑）
//   反例 RV：把"已生成可再改"打开 ⇒ 第二次写宣言应红；把最短字数改成 0 ⇒ 空话合格 ⇒ 红。
import { 设置存储, 写理由, 理由合格, 缺哪些, 理由齐了吗, 读理由, 写宣言, 读宣言, 宣言合格, 可读摘要, 清空取舍, 取舍项, 理由最短 } from '../src/choiceReasons.mjs'

// 假存储（Node 无 localStorage）
const map = new Map()
设置存储({ getItem: k => (map.has(k) ? map.get(k) : null), setItem: (k, v) => map.set(k, String(v)) })

const bad = []
let 检查数 = 0
const ok = (cond, msg) => { 检查数++; if (!cond) bad.push(msg) }

// ① 字数下限
ok(理由合格('随便') === false, '过短（2 字）不算合格')
ok(理由合格('x'.repeat(理由最短)) === true, `${理由最短} 字应合格`)
ok(理由合格('') === false && 理由合格(null) === false, '空/ null 不合格')

// ② 写理由 + 缺项点名
写理由('bizMode', '选 OTA 是因为新店无品牌客源，先借平台流量换订单，佣金换曝光')
ok(理由合格(读理由().bizMode.text), '写进去的理由应合格')
ok(缺哪些().length === 取舍项.length - 1, `缺项应点名其余 ${取舍项.length - 1} 项（实得 ${缺哪些().length}）`)
ok(理由齐了吗() === false, '还没写齐')

// ③ 没写齐 ⇒ 宣言不许生成（并点名缺哪些）
{
  const r = 写宣言({ 预算分配: '装修降一档换现金', 最大赌注: '押商务客', 最怕: '出租率' })
  ok(r.成功 === false && /还没写完取舍理由/.test(r.原因), '缺理由时生成宣言应失败并点名')
  ok(读宣言() === null, '失败时不得写入任何宣言')
}
写理由('property', '选交通枢纽是因为测算 78 间过线，且租金低，牺牲的是商圈溢价')
写理由('brand', '选汉庭而不是全季/海友：全季预算装不下，海友房价天花板太低，汉庭居中')
写理由('invest', '装修降档省下的钱不升级软装，留给第 1 周现金流，赌开业后的现金安全')
ok(理由齐了吗() === true, '四项写齐后应就绪')

// ④ 宣言：时间戳 + 不可编辑
{
  const r = 写宣言({ 预算分配: '装修低档 + 其余中档', 最大赌注: '先活过前 4 周', 最怕: '差评发酵打垮口碑' })
  ok(r.成功 === true, '写齐理由 + 三个字段应生成成功')
  const d = 读宣言()
  ok(宣言合格(d), '生成的宣言应合格（含 ISO 时间戳与三个字段）')
  ok(/^\d{4}-\d{2}-\d{2}T/.test(d.at), `时间戳应为 ISO（实得 ${d.at}）`)
  ok(d.理由 && Object.keys(d.理由).length === 取舍项.length, '宣言应快照全部取舍理由（事后对照用）')
  const r2 = 写宣言({ 预算分配: '改主意了', 最大赌注: 'x', 最怕: 'y' })
  ok(r2.成功 === false && /不可编辑/.test(r2.原因), '宣言已生成后不得再改')
  ok(读宣言().预算分配 === '装修低档 + 其余中档', '第二次写不得覆盖第一次')
}

// ⑤ 可读摘要（教师端/复盘）
{
  const s = 可读摘要()
  ok(s.理由.length === 取舍项.length && s.理由.every(x => x.写了), '摘要应逐项标出已写')
  ok(s.宣言 && s.宣言.at, '摘要应带宣言时间戳')
  ok(s.缺.length === 0, '写齐后缺项为空')
}

// ⑥ 清空（重开一局）
清空取舍()
ok(Object.keys(读理由()).length === 0 && 读宣言() === null, '清空后理由与宣言都应没了')

console.log('══ V113-1.3 取舍句 + 开店宣言 ══')
console.log(`  ${取舍项.length} 项理由 · 最短 ${理由最短} 字 · 宣言一次生成（不可编辑）· 时间戳 ISO`)
for (const b of bad.slice(0, 8)) console.log('  ✗ ' + b)
console.log(`结果: ${检查数 - bad.length} 通过 / ${bad.length} 失败`)
process.exit(bad.length === 0 ? 0 : 1)
