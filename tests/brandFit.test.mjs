// V113-1.2 判据：品牌互斥（预算装不下 / 房量装不下 / 无法核算 三态分明）
//   反例 RV：把预算调到极大 ⇒ 预算装不下消失（全"可行"）；
//            把房量门槛调 0 ⇒ 房量装不下消失 ⇒ 红（本套件用"人工构造 brand 门槛不存在"验证第三态）。
import { 品牌可行性, 房量装得下 } from '../src/brandFit.mjs'
import { 筹建预算默认 } from '../src/startupBudget.mjs'

const bad = []
let 检查数 = 0
const ok = (cond, msg) => { 检查数++; if (!cond) bad.push(msg) }

// ① 预算口径：在 6,000,000 元下，汉庭/海友可行、全季超预算（举证）
const 汉庭 = 品牌可行性({ name: '汉庭', standard: '客房70间起' })
const 全季 = 品牌可行性({ name: '全季', standard: '客房80间起' })
const 海友 = 品牌可行性({ name: '海友', standard: '客房40间起' })
ok(汉庭.状态 === '可行', `汉庭应可行（实得 ${汉庭.状态} · ${汉庭.原因}）`)
ok(海友.状态 === '可行', `海友应可行（实得 ${海友.状态}）`)
ok(全季.状态 === '超预算', `全季应超预算（实得 ${全季.状态} · 最低 ${全季.最低投资}）`)
ok(全季.缺口 > 0 && 全季.最低投资 - 全季.预算 === 全季.缺口, '超预算的缺口 = 最低投资 − 预算')
// 存在"装不下"的品牌组合 ⇒ 判据 §4-1.2 有举证
ok([汉庭, 全季, 海友].some(x => x.状态 === '超预算'), '同一预算下必须**存在**装不下的品牌（判据 1.2）')
ok([汉庭, 全季, 海友].some(x => x.状态 === '可行'), '同一预算下也必须**存在**装得下的品牌（否则课堂锁死）')

// ② 无法核算：费率未接入的品牌不得被当成"可行/超预算"
{
  const x = 品牌可行性({ name: '桔子', standard: '客房60间起' })
  ok(x.状态 === '无法核算', `费率未接入品牌应为"无法核算"（实得 ${x.状态}）`)
  ok(x.最低投资 === null, '无法核算时 最低投资 必须为 null（不编）')
  ok(/费率|造价/.test(x.原因), '无法核算必须点名缺什么')
}

// ③ 房量门槛：汉庭最少 70 间 ⇒ 68 间装不下、78 间装得下
const 小 = 房量装得下({ name: '汉庭' }, 68)
const 大 = 房量装得下({ name: '汉庭' }, 78)
ok(小.装得下 === false && /最少 70/.test(小.原因), `68 间应装不下汉庭（实得 ${JSON.stringify(小)}）`)
ok(大.装得下 === true, `78 间应装得下汉庭（实得 ${JSON.stringify(大)}）`)
ok(房量装得下({ name: '汉庭' }, null).装得下 === null, '未测算房量 ⇒ 不该判"装不下的"（应为 null）')
ok(房量装得下({ name: '不存在的品牌' }, 80).装得下 === null, '门槛数据缺失 ⇒ null（不猜）')

console.log('══ V113-1.2 品牌互斥 ══')
console.log(`  预算 ${(筹建预算默认 / 10000).toFixed(0)} 万：汉庭 ${汉庭.状态}（最低 ${(汉庭.最低投资 / 10000).toFixed(0)} 万）· 海友 ${海友.状态}（${(海友.最低投资 / 10000).toFixed(0)} 万）· 全季 ${全季.状态}（差 ${(全季.缺口 / 10000).toFixed(0)} 万）`)
console.log(`  房量：68 间 → ${小.原因}`)
console.log(`        78 间 → ${大.原因}`)
for (const b of bad.slice(0, 8)) console.log('  ✗ ' + b)
console.log(`结果: ${检查数 - bad.length} 通过 / ${bad.length} 失败`)
process.exit(bad.length === 0 ? 0 : 1)
