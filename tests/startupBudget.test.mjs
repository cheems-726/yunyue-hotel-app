// V113-1.1 判据：筹建预算包（超预算闸 + 放弃清单用真实差额）
//   反例 RV：把预算调到极大 ⇒ 全中档也"畅行"（超支恒 0）；把 放弃清单 改成各档常量 ⇒ 真实差额红。
import { 筹建账, 放弃清单, 筹建预算默认 } from '../src/startupBudget.mjs'
import { 投资测算 } from '../src/establishmentInvest.mjs'

const bad = []
let 检查数 = 0
const ok = (cond, msg) => { 检查数++; if (!cond) bad.push(msg) }

const 汉庭 = { name: '汉庭', level: '经济型', standard: '客房70间起' }
const 全中 = { 装修: '中', 软装: '中', IT: '中', 布草: '中', 开办费: '中' }
const 全低 = { 装修: '低', 软装: '低', IT: '低', 布草: '低', 开办费: '低' }

ok(筹建预算默认 === 6000000, `预算默认应为 600 万（实得 ${筹建预算默认}）`)

const 中 = 筹建账({ brand: 汉庭, 选择: 全中 })
const 低 = 筹建账({ brand: 汉庭, 选择: 全低 })

ok(中.五项 === 投资测算({ brand: 汉庭, 选择: 全中 }).合计, '五项应与 投资测算 同源（单源）')
ok(中.一次性 > 0 && 中.保证金 > 0, '一次性费用与保证金应取自 franchiseFees（不另算）')
ok(中.合计 === 中.五项 + 中.一次性, '合计 = 五项 + 一次性')
ok(中.剩余 === 中.预算 - 中.合计, '剩余 = 预算 − 合计')
ok(中.超支 > 0 && 中.可过 === false, `全中档必须超预算（超支 ${(中.超支 / 10000).toFixed(1)} 万）`)
ok(低.合计 < 中.合计 && 低.可过 === true, `全低档应在预算内（合计 ${(低.合计 / 10000).toFixed(1)} 万）`)
ok(低.超支 === 0 && 低.剩余 > 0, '全低档：超支 0 且有余量')

// 降一档能救回来（至少一种单点降档组合能过线）—— 证明闸是"可解的取舍"而不是死路
{
  const 候选 = []
  for (const k of Object.keys(全中)) {
    const 账 = 筹建账({ brand: 汉庭, 选择: { ...全中, [k]: '低' } })
    候选.push({ k, 可过: 账.可过, 超: 账.超支 })
  }
  // 全低已能过 ⇒ 至少存在可行解
  ok(低.可过, '必须存在可行解（否则闸门把课堂锁死）')
  检查数++  // 记录候选（不判）
  console.log('  单点降一档：' + 候选.map(c => `${c.k}→低 ${c.可过 ? '过' : '仍超' + (c.超 / 10000).toFixed(1) + '万'}`).join(' · '))
}

// 放弃清单：真实差额（等于"该档 vs 低档"的 投资测算 差）
{
  const 清单 = 放弃清单({ brand: 汉庭, 选择: 全中 })
  ok(清单.length === 5, `全中档应列出 5 项"放弃"（实得 ${清单.length}）`)
  for (const x of 清单) {
    const 差 = 投资测算({ brand: 汉庭, 选择: 全中 }).合计 - 投资测算({ brand: 汉庭, 选择: { ...全中, [x.项]: '低' } }).合计
    ok(x.多花 === 差, `${x.项} 的多花额应为真实差额（${x.多花} vs ${差}）`)
    ok(x.多花 > 0, `${x.项} 的差额应为正`)
  }
  ok(放弃清单({ brand: 汉庭, 选择: 全低 }).length === 0, '全低档 ⇒ 没有"放弃"项（都是最低档）')
}

// 缺来源品牌 ⇒ 不编：合计 null、可过 false、缺项 true
{
  const 账 = 筹建账({ brand: { name: '不存在的品牌', standard: '客房70间起' }, 选择: 全中 })
  ok(账.合计 === null && 账.缺项 === true && 账.可过 === false, '缺造价 ⇒ 合计 null / 缺项 / 不可过（不编）')
}

console.log('══ V113-1.1 筹建预算包 ══')
console.log(`  预算 ${(中.预算 / 10000).toFixed(1)} 万 · 全中档 ${(中.合计 / 10000).toFixed(1)} 万（超 ${(中.超支 / 10000).toFixed(1)} 万）· 全低档 ${(低.合计 / 10000).toFixed(1)} 万（余 ${(低.剩余 / 10000).toFixed(1)} 万）`)
console.log(`  放弃清单（全中）：${放弃清单({ brand: 汉庭, 选择: 全中 }).map(x => x.项 + ' ' + (x.多花 / 10000).toFixed(1) + '万').join(' · ')}`)
for (const b of bad.slice(0, 8)) console.log('  ✗ ' + b)
console.log(`结果: ${检查数 - bad.length} 通过 / ${bad.length} 失败`)
process.exit(bad.length === 0 ? 0 : 1)
