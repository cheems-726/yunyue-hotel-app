// A1 返修 ①②：门禁数字比对【唯一实现点】（纯函数，供 docs-sync 与自检共用）
// 口径：**精确相等**（无容差）。理由（返修②）：百分比容差会放过"差 24"的真过期数字，
//   而"本套件自身断言数波动"的问题改由【记录写入策略】解决（见 run-all 的记录条件），
//   不靠容差掩盖 —— 容差既不唯一也不可解释，故整体删除。
//
// 为什么单列一个模块：让"比对来源唯一"可被断言证明（返修①的验收要求）。
export const 数字匹配 = (卡数字数组, 记录值) =>
  Array.isArray(卡数字数组) && Number.isFinite(记录值) && 卡数字数组.includes(记录值)

// 从卡的一段文本里抽出候选数字（≥3 位，避免版本号/周次等噪声）
export const 抽数字 = (文本) => (String(文本).match(/\b\d{3,}\b/g) || []).map(Number)
