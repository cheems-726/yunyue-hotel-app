// 学期长度单源（§22.2-B2 前置 · "期末"钩子的时间基准）
//
// ── 为什么需要本模块 ────────────────────────────────────────────
//   "期末"必须**恰好一处定义**：引擎的保证金退还钩子（settlement）、结业判定（App）、
//   成绩页（FinalResult）都要用同一个数 —— 否则"退还周"和"结业周"错位 = 假账（D55-a 同族）。
//
// ── ★ 与 §19.2 文本的差异（执行端核对权威源后纠正 · 需决策端复核）────────
//   §19.2/§21.2 写"期末 = 第 18 周（第 126 天）"——该数字来自【长跑测试】（longRun126 = 18 周），
//   而**产品的教学学期是 12 周**（FinalResult.TOTAL_WEEKS=12 · App "week >= 12 ⇒ finished" ·
//   界面文案"第 N / 12 周"· 帮助页"经营一家酒店 12 周"）。
//   ⇒ 若照"18 周"实现，学生 12 周结业时**保证金永远没机会退** ⇒ "期末可退"变成假账。
//   ⇒ 本模块按【产品现实】定 TOTAL_WEEKS = 12，并把"第 126 天"视为长跑口径的串写。
//   ★ 这不是"另立时间概念"——恰恰是把"期末"钉在既有的结业口径（week 12）上，单源化。
export const TOTAL_WEEKS = 12
export const TOTAL_DAYS = TOTAL_WEEKS * 7
export const 学期口径说明 = '教学学期 = 12 周（FinalResult/ App 结业判定同源）；"18 周/126 天"是长跑测试（longRun126）的长度，不是学期'
