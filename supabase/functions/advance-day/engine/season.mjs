// 取某教学周的季节（越界：按表内最接近的值外推 —— 12 周固定学期，越界属异常数据，取末周并如实标注）
export function 季节(week) {
  const w = Math.max(1, Math.round(Number(week) || 1))
  const 行 = SEASON_TABLE.find(r => r.周 === w) || (w > SEASON_TABLE.length ? SEASON_TABLE[SEASON_TABLE.length - 1] : SEASON_TABLE[0])
  return { ...行, 周: w, 越界: w > SEASON_TABLE.length }
}

export function 季节因子(week) {
  const f = Number(季节(week).因子)
  return Number.isFinite(f) ? f : 1
}

// 面板/周报文案（唯一生成点）
export function 季节文案(week) {
  const s = 季节(week)
  const 偏差 = Math.round((s.因子 - 1) * 100)
  return {
    ...s,
    文案: 偏差 === 0 ? `本周为${s.名}（需求无额外起伏）` : `本周为${s.名} → 需求 ${偏差 > 0 ? '+' : ''}${偏差}%`,
    系数: s.因子,
  }
}

// 同一周全班是否同季节（守门用 · 也是公平性口径的机器表述）
export const 全班同季节 = (week) => 季节因子(week)
