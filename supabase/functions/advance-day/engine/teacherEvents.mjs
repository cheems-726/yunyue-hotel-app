// 按注入参数生成事件条目（settle 消费的形状 · 纯函数 · 确定性）
export function 构建注入事件({ 事件id, 周, injectedBy, injectedAt }) {
  const 库 = 注入事件库.find(e => e.id === 事件id)
  if (!库) return null
  if (!Number.isFinite(Number(周)) || Number(周) < 1) return null
  return {
    id: `t-${事件id}-w${周}`,
    来源事件: 事件id,
    name: `老师注入 · ${库.name}`,
    icon: 库.icon,
    type: 'bad',
    week: Number(周),
    source: 'teacher',
    injectedBy: injectedBy || 'teacher',
    injectedAt: injectedAt || null,
    text: 库.描述 ? `${库.描述}｜影响：${库.影响}` : 库.影响,   // ★ V78：学生端能看到「发生了什么（描述）+ 影响幅度」；为什么=tip（教学点）
    tip: 库.教学点,
    // ★ §33-V8：E9+ 事件带 engine（v8:true 标记）⇒ 引擎通用效力通道消费（客流/成本/属性/罚款）。
    //   E1–E8 的 engine 是【文档性】的（引擎按 ID 硬编码消费），此处带不带都行；带上以统一形状。
    ...(库.engine ? { engine: 库.engine } : {}),
  }
}

// ★ 应对选项查询（界面单源）：未知事件 ⇒ 空数组（界面自行处理"无选项"）
export function 应对选项Of(事件id) {
  const 库 = 注入事件库.find(e => e.id === 事件id)
  return Array.isArray(库 && 库.应对选项) ? 库.应对选项 : []
}

// ★ 该事件的应对是否【有数值分支】（一处生效：E8 经危机通道；其余一期=记录/复盘）
export function 应对可执行Of(事件id) {
  const 库 = 注入事件库.find(e => e.id === 事件id)
  return !!(库 && 库.应对可执行)
}

// ★ 公平红线 (a)：只影响未来 —— 注入周必须 > 该组已结算周（否则返回非法）
export function 校验注入合法性({ 注入周, 已结算周 }) {
  const n = Number(注入周), done = Number(已结算周)
  if (!Number.isFinite(n) || n < 1) return { 合法: false, 原因: '注入周非法' }
  if (Number.isFinite(done) && n <= done) return { 合法: false, 原因: `不能改已结算周（第 ${done} 周已结算，注入周必须 > ${done}）` }
  return { 合法: true }
}

// ★ 公平红线 (c)：离线补算跨过事件周 ⇒ 按「默认最差」处理 + 标注文案（唯一生成点）
