//   选择形态: [{ 维度key, 方向(仅带方向维度需要: '升'|'降'), 档位('小'|'中'|'大') }]
export function 效力选择转引擎(选择 = []) {
  const engine = { v8: true }
  const 文案s = []
  for (const sel of (Array.isArray(选择) ? 选择 : []).slice(0, 3)) {   // ★ 最多 3 个维度
    const d = 效力维度.find(x => x.key === sel.维度key)
    if (!d || !d.档[sel.档位]) continue
    let 值 = d.档[sel.档位]
    let 文案 = d.文案[sel.档位]
    if (d.带方向) {
      const 降 = sel.方向 === '降'
      值 = 降 ? -值 : 值
      文案 = 降 ? 文案.replace('±', '−') : 文案.replace('±', '+')
    }
    if (d.维度 === '品质' || d.维度 === '声誉' || d.维度 === '士气' || d.维度 === '罚款') {
      // 加法维度（属性 ∓N / 罚款金额）：同类累加（老师选两个属性维度 ⇒ 叠加 · 上限 3 个维度已控）
      engine[d.维度] = (Number(engine[d.维度]) || 0) + 值
    } else {
      // 乘法维度（客流/成本系数）：连乘
      engine[d.维度] = (Number.isFinite(Number(engine[d.维度])) && Number(engine[d.维度]) > 0 ? Number(engine[d.维度]) : 1) * 值
    }
    文案s.push(文案)
  }
  return { engine, 效力文案: 文案s.join(' · ') || '纯叙事（无数值效力）' }
}

// 构建自定义事件（老师自己写正文 + 受控效力）—— 与 构建注入事件 同形状（共用生效通道）
export function 构建自定义事件({ 定义, 周, 生效日 = null, injectedBy, injectedAt }) {
  if (!定义 || typeof 定义 !== 'object') return null
  const 标题 = String(定义.标题 || '').trim()
  const 正文 = String(定义.正文 || '').trim()
  if (!标题 || !正文) return null
  if (!Number.isFinite(Number(周)) || Number(周) < 1) return null
  const { engine, 效力文案 } = 效力选择转引擎(定义.效力)
  return {
    id: `t-custom-w${周}-${String(标题).slice(0, 12)}`,
    来源事件: `CUSTOM:${标题.slice(0, 20)}`,
    name: `📌 老师注入 · ${标题}`,
    icon: String(定义.图标 || '📌'),
    type: 'bad',
    week: Number(周),
    ...(Number.isFinite(Number(生效日)) && Number(生效日) >= 1 && Number(生效日) <= 7 ? { 生效日: Number(生效日) } : {}),
    source: 'teacher',
    自定义: true,
    injectedBy: injectedBy || 'teacher',
    injectedAt: injectedAt || null,
    text: `${正文}（这是老师注入的突发事件 · 30 秒内选择你的应对）${效力文案 !== '纯叙事（无数值效力）' ? ` ｜ 效力：${效力文案}` : ''} ｜ 注入人：${injectedBy || '老师'}`,
    tip: String(定义.教学点 || ''),
    教学点: String(定义.教学点 || ''),
    备注: String(定义.备注 || ''),
    应对选项: Array.isArray(定义.应对选项) && 定义.应对选项.length >= 2 ? 定义.应对选项 : [{ label: '积极应对' }, { label: '按常规处理' }],
    engine,
  }
}

// 按日程触发校验（公平红线 a 的天粒度版）：注入周必须 ≥ 当前教学周；同周内 生效日 必须 ≥ 当前 dayIndex（不得改已过去的天）
export function 校验按日触发({ 注入周, 生效日, 当前教学周, 当前dayIndex }) {
  const 周检 = 校验注入合法性({ 注入周, 已结算周: Math.max(0, Number(当前教学周) - 1) })
  if (!周检.合法) return 周检
  const d = Number(生效日)
  if (!Number.isFinite(Number(注入周))) return { 合法: false, 原因: '注入周非法' }
  if (Number(注入周) === Number(当前教学周) && Number.isFinite(d) && d > 1 && Number.isFinite(Number(当前dayIndex)) && d <= Number(当前dayIndex)) {
    return { 合法: false, 原因: `生效日（第 ${d} 天）已过去（当前第 ${当前dayIndex} 天）—— 只影响未来` }
  }
  return { 合法: true }
}
