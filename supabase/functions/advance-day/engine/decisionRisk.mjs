export const 决策总项数 = 18

// 不作为的属性扣减（缺 n 项 ⇒ 按上限夹取；缺 0 项 ⇒ 空对象）
export function 不作为属性扣减(已决策项数) {
  const 缺 = Math.max(0, 决策总项数 - (Number(已决策项数) || 0))
  const n = Math.min(缺, 不作为惩罚.上限项数)
  if (!n) return {}
  // ★ 为 0 的项**不添键**（条件挂载纪律：0 代价不该让返回值多出键 —— 水位线靠这一条保持）
  const 扣 = {}
  const m = 不作为惩罚.每项.morale * n
  const q = 不作为惩罚.每项.quality * n
  if (m) 扣.morale = m
  if (q) 扣.quality = q
  return 扣
}

// 本周决策集合 ⇒ 下周惩罚（条件挂载：无 ⇒ null ⇒ settle 不添键）
//   ★ 只取**本周真的做了**的项；未决策的项由 不作为惩罚 当周结算（不在延迟里重复扣）
export function 本周延迟惩罚(decisions = {}) {
  const 项 = []
  for (const [id, ans] of Object.entries(decisions || {})) {
    const 延 = 延迟后果(id, ans)
    if (!延) continue
    const 属性 = Object.fromEntries(Object.entries(延).filter(([k]) => 属性清单.includes(k)))
    if (Object.keys(属性).length) 项.push({ 来源: id, 文案: 延.文案 || '', 属性 })
  }
  return 项.length ? { 项 } : null
}
