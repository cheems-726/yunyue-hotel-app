// ── 选项键解析器（唯一入口 · 纯函数）────────────────────────────
//   存档里答案有 5 种形状：option(字符串) · slider(数值) · budget(对象) · sort(数组) · 计算型(数值)
//   ★ 解析不出来 ⇒ null（调用方按「未登记」处理，绝不抛异常 —— 旧档/脏档也要能跑）
export function 选项键(decisionId, answer) {
  const d = 代价表[decisionId]
  if (!d) return null
  const 表 = d.选项
  const 有 = (k) => Object.prototype.hasOwnProperty.call(表, k) ? k : null
  if (decisionId === 'quality-check') return 有(Array.isArray(answer) && answer.length ? '已提交质检' : '未提交质检')
  if (decisionId === 'overbook') {
    const v = Number(answer)
    if (!Number.isFinite(v)) return null
    return 有(v > 0 ? '超售（>0 间）' : '不超售（0 间）')
  }
  if (decisionId === 'energy') {
    const v = Number(answer)
    if (!Number.isFinite(v)) return null
    return 有(v <= 21 ? '偏冷（≤21℃）' : v >= 25 ? '偏热（≥25℃）' : '舒适区间（22–24℃）')
  }
  if (decisionId === 'member-threshold') {
    const v = Number(answer)
    if (!Number.isFinite(v)) return null
    return 有(v <= 4 ? '门槛低（3–4 晚）' : v >= 8 ? '门槛高（8–10 晚）' : '门槛适中（5–7 晚）')
  }
  if (decisionId === 'ota') {
    if (!answer || typeof answer !== 'object') return null
    const vals = Object.values(answer).map(Number).filter(Number.isFinite)
    if (!vals.length) return null
    const total = vals.reduce((a, b) => a + b, 0)
    if (total <= 0) return null
    const top = Math.max(...vals)
    return 有(top / total >= 0.6 ? '集中投放' : '均衡投放')
  }
  if (decisionId === 'campaign') {
    // ★ §32-U4c（硬伤③同族修正）：**对象形状 ⇒ 已选**（哪怕空/全 0 = "没分"也是一次拍板 ⇒ 有代价）；
    //   null/undefined ⇒ 未决策（返回 null 走"不作为"路径，不冒充"未分配预算"）。
    //   原写法要求"非空且 >0"⇒「未分配预算」条目**永远不可达** ⇒ 该分支成了无代价的纯收益分支（实测抓到）。
    if (answer === null || answer === undefined) return null
    if (typeof answer !== 'object') return null
    const vals = Object.values(answer).map(Number).filter(Number.isFinite)
    return 有(vals.length && vals.reduce((a, b) => a + b, 0) > 0 ? '已分配预算' : '未分配预算')
  }
  if (typeof answer !== 'string') return null
  return 有(answer)
}

// 某项决策在某答案下的代价条目（未登记 ⇒ null）
export function 选项代价(decisionId, answer) {
  const k = 选项键(decisionId, answer)
  return k ? 代价表[decisionId].选项[k] : null
}

// 属性代价（给 attrs.js 用；无 ⇒ 空对象）
export function 属性代价(decisionId, answer) {
  const e = 选项代价(decisionId, answer)
  return (e && e.属性) || {}
}

// 延迟后果（下周属性惩罚；无 ⇒ null）
export function 延迟后果(decisionId, answer) {
  const e = 选项代价(decisionId, answer)
  return (e && e.延迟) || null
}

// 界面文案：选项的代价行（DecisionPanel 渲染 · 唯一生成点）
export function 代价文案(decisionId, answer) {
  const e = 选项代价(decisionId, answer)
  return e ? '代价：' + e.代价 : null
}

