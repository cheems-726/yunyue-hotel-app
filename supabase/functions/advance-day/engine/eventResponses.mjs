/** 无应对空间的事件（库里没有 `条件`）—— 显式声明，不是漏填 */
export const 无应对空间 = (事件id, 库) => {
  const e = (库 || []).find(x => x.id === 事件id)
  return !!(e && !e.条件 && !应对映射[事件id])
}

/**
 * 某事件 + 某应对 ⇒ 效力
 * @returns {{可执行:boolean, 通道:string|null, 效力:object|null, 文案:string, 原因?:string}}
 */
export function 应对效力Of(事件id, 应对值, 库 = []) {
  const m = 应对映射[事件id]
  if (m) {
    const v = m.选项[String(应对值 || '')]
    if (!v) return { 可执行: false, 通道: m.通道, 效力: null, 文案: '这个应对在本事件里没有定义（未知值必须报错，不许静默回退）', 原因: '未知应对值' }
    return { 可执行: true, 通道: m.通道, 效力: v.效力, 文案: v.文案 }
  }
  if (无应对空间(事件id, 库)) return { 可执行: false, 通道: null, 效力: null, 文案: '此事没有可选应对（纯环境事件）', 原因: '无应对空间' }
  return { 可执行: false, 通道: null, 效力: null, 文案: '该事件尚未定义应对效力', 原因: '未定义' }
}

/** 可执行映射统计（守门用）：已接线 / 危机分支已有 / 仍需扩引擎 */
export function 映射统计() {
  const ids = Object.keys(应对映射)
  return {
    事件数: ids.length,
    需扩引擎: ids.filter(k => 应对映射[k].通道 === '需扩引擎'),
    已接线: ids.filter(k => 应对映射[k].通道 === '已接线'),
    已通: ids.filter(k => 应对映射[k].通道 === '危机分支已有'),
  }
}
