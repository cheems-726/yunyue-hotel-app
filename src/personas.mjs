// V121 · 六性格决策模型（**纯函数 · 种子固定 · 可复现**）
//
// 目标：一个学期的决策由**人格自己长出来**，不是轮转注入；每周给出**人话理由**（≤50 字）。
// 三条硬要求（卡上 §2）：① 能讲理由 ② 要犯错（每组每学期 ≥2 次"人格使然的不利选择"）
//   ③ 要有反应（读到上周差评 ⇒ 下周必须变；数据驱动组最明显，躺平组几乎不变）
//
// 边界：本模块**不写库、不结算**；它只产出「每周决策 + 理由 + 是否犯错」，
//   结算与终局分化由跑测脚本（测试机）负责。

