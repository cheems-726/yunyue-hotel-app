  pricing: ['提价 50%', '不跟降', '降价 20% 抢客', '跟降 10%'],
  campaign: ['做活动', '不做活动'],
  overbook: ['超售 5 间', '超售 3 间', '不超售'],
  hygiene: ['停房深清洁', '标准'],
  linen: ['自洗', '外包'],
