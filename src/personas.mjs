/**
 * 一组一周的决策
 * @param {number} 组号 1..6
 * @param {number} week 1..12
 * @param {{差评?:number, 出租?:number, gop率?:number, 亏损?:boolean}} 上周 上周结果（第 1 周为空）
 * @param {number} 随机 0..1（种子固定后由调用方给）
 */
export function 生成周决策(组号, week, 上周 = {}, 随机 = 0.5) {
  const p = 人格[组号]
  const 决策 = { ...p.基准 }
  const s = { 差评: Number(上周.差评) || 0, 出租: Number(上周.出租) || 60, gop率: Number(上周.gop率) || 0.35, 亏损: !!上周.亏损 }
  let 犯错 = false

  // ③ 反应：上周有差评 / 亏损 ⇒ 按人格强度调整
  if (week > 1) {
    if (s.差评 >= 2 && 随机 < p.反应) {
      // 强反应人格会改（品质/卫生/口碑相关）；躺平组几乎不动
      决策.campaign = '不做活动'
      if (组号 === 4) 决策.hygiene = '停房深清洁'
    }
    if (s.亏损 && 随机 < p.反应 * 0.8) {
      决策.campaign = '不做活动'
      if (组号 !== 1) 决策.pricing = '不跟降'
    }
    if (组号 === 5 && s.gop率 < 0.28) 决策.campaign = '不做活动'
  }

  // ② 犯错：人格使然的不利选择（每组每学期至少 2 次，由 week 与人格决定，可复现）
  if (week >= 3 && (week + 组号) % 4 === 0) {
    const 方 = 犯错方向[组号]
    if (方) { 决策[方.key] = 方.值; 犯错 = true }
  }

  // ③b 每周微调：按上周指标动一档（反应强的人格动得多，躺平几乎不动）
  if (week > 1) {
    const 档 = 可调项.pricing
    const 级 = Math.max(0, 档.indexOf(决策.pricing))
    let 调 = 0
    if (s.出租 < 55) 调 = -1
    else if (s.出租 > 72) 调 = +1
    else 调 = 随机 < 0.5 ? -1 : +1
    if (随机 < p.反应) 决策.pricing = 档[Math.max(0, Math.min(档.length - 1, 级 + 调))]
  }
  // 能耗每周都在动（最基础的有变化）
  决策.energy = 22 + ((week + 组号) % 4)

  // 完成度：躺平组只填 30–35% 的项
  const 项s = Object.keys(决策)
  const 填数 = Math.max(1, Math.round(项s.length * p.完成率))
  const 完成 = 项s.slice(0, 填数)

  const 理由 = 犯错 ? 犯错理由[组号] : 理由句[组号](s)
  return { 组号, week, 决策, 完成项: 完成, 完成率: 完成.length / 项s.length, 犯错, 理由: String(理由).slice(0, 50) }
}
