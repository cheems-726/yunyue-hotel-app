/**
 * 筹建账
 * @param {{brand:object, 选择?:object}} p 选择 = investTiers（装修/软装/IT/布草/开办费 各 低中高）
 * @returns {{预算, 五项, 一次性, 保证金, 合计, 剩余, 超支, 可过, 缺项:boolean}}
 */
export function 筹建账({ brand, 选择 } = {}) {
  const 测 = 投资测算({ brand, 选择 })
  const 一次 = 一次性费用清单(brand)
  const 五项 = Number.isFinite(测.合计) ? 测.合计 : null
  const 一次性合计 = 一次 && Number.isFinite(一次.合计) ? 一次.合计 : null
  const 缺项 = 五项 == null || 一次性合计 == null
  const 合计 = 缺项 ? null : 五项 + 一次性合计
  const 预算 = 筹建预算默认
  const 剩余 = 合计 == null ? null : 预算 - 合计
  const 超支 = 合计 != null && 合计 > 预算 ? 合计 - 预算 : 0
  return {
    预算, 五项, 一次性: 一次性合计,
    保证金: 一次 ? (一次.保证金 ?? 0) : 0,
    合计, 剩余, 超支,
    可过: 合计 != null && 超支 === 0,
    缺项,
  }
}

/**
 * 「你放弃了什么」——每个**高于低档**的选择，列出"比低档多花多少"（用真实差额：走 投资测算 重算）
 *   ★ 为什么逐个重算而不是读比例：装修档会改变四项附加的基数 ⇒ 只有重算才是真实差额
 * @returns {Array<{项:string, 当前:string, 多花:number}>}
 */
export function 放弃清单({ brand, 选择 } = {}) {
  const 项s = ['装修', '软装', 'IT', '布草', '开办费']
  const 基 = 选择 && typeof 选择 === 'object' ? 选择 : {}
  const 全 = 投资测算({ brand, 选择: 基 }).合计
  if (!Number.isFinite(全)) return []
  const out = []
  for (const 项 of 项s) {
    const 当 = 基[项] || '中'
    if (当 === '低') continue
    const 低 = 投资测算({ brand, 选择: { ...基, [项]: '低' } }).合计
    if (!Number.isFinite(低)) continue
    const 多花 = 全 - 低
    if (多花 > 0) out.push({ 项, 当前: 当, 多花 })
  }
  return out
}
