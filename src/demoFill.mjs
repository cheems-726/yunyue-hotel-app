export function 档次(品牌名) {
  const n = String(品牌名 || '').trim()
  if (品牌档次[n]) return 品牌档次[n]
  if (/禧玥|花间堂|施柏阁|诺富特/.test(n)) return '高档'
  if (/美仑|漫心|水晶|CitiGO|宋品|永乐/.test(n)) return '中高档'
  if (/全季|桔子|星程|城际/.test(n)) return '中档'
  return '经济型'
}

/** 取该品牌的演示设定值（永不为 null —— 这是本模块存在的意义） */
export function 演示值(品牌名) {
  if (!DEMO_FILL) return null
  const t = 演示档次表[档次(品牌名)]
  return { ...t, 档次: 档次(品牌名), 来源: '演示设定（非官方数据 · D367）' }
}

