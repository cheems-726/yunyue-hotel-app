// §14.3 · G3 第二步：加盟费率进资金流（引擎侧【唯一计算点】）
//
// ── 依据（决策端代拍 · 2026-09-28）────────────────────────────────
//   D53-a 接入范围：只接【汉庭 / 全季 / 海友】（费率来源完整）；其余品牌一律"待补"，不编造
//   D53-b 费率方式：按营收百分比计提（管理费 + CRS），不引入"固定月费"新口径
//   D53-c capex（投资额）：不进 E1 账本（另立概念，后续批次）
//   ★ 关键证据（决策端）：管理费 + CRS ≈ 营收 7.4% ⇒ 六组排序不变（只整体下移）
//     ⇒ 本文件把该证据固化成断言（tests/franchiseFees.test.mjs：两费率合计 7.40%）
//
// ── 三条硬纪律 ────────────────────────────────────────────────
//   ★ 单源：本文件是加盟费用在引擎里的【唯一计算点】。周报成本构成 / 一页钱账 / 断言
//     都读这里的结果，不许另写一份公式（E1 账本单源 · D53 要求）。
//   ★ 零变化：未接入品牌 ⇒ franchiseFees() 返回 null ⇒ 结算输出【逐字节不变】
//     （守门：与 §14.3 接线【之前】冻结的 fixture 逐字节比对 —— 见 tests/fixtures/settle-baseline-14.3.json）
//   ★ 不消耗 rand()：本文件是纯算术，不抽随机数 ⇒ 事件/差评/竞品的随机序列完全不受影响
//     （公平性红线：加了费用不会顺带改掉任何非货币结果）
//
// ── 本轮【不进资金流】的科目（如实标注，不静默省略）─────────────────
//   加盟费 / 保证金 / 筹备费 / PMS：属【筹建期一次性】。为什么不本轮接：
//   ① 决策端口径已定"分两步：先收月度费率（口径干净、不用动 IC）"（参数表 §三·结论 4）
//   ② 保证金要"期末可退"，引擎现在【没有期末钩子】—— 硬接会把"退没退"变成假账
//   ③ 一次性费用从 IC 里扣会跟 D49-g 刚正名的「运营启动资金 = 我手里的钱」搅在一起
//   ④ 这四项已在【认领页报价单】按投资侧列示（propertyQuote）⇒ 并非学生看不到
//   ⇒ 已列《待决策队列》A 级（见队列"一次性费用是否进 IC"），待决策端拍板后再接。
import { FRANCHISE_MODEL } from './franchiseModel.mjs'

// ── 接入范围（D53-a）──────────────────────────────────────────
export const 已接入品牌 = ['汉庭', '全季', '海友']
export const 接入范围说明 = '只接费率来源完整的三个品牌；其余品牌保持"待补"（不拿别家费率冒充）'

// ── CRS 有效费率折算 ──────────────────────────────────────────
// 加盟资料给的 8% 是【中央预订系统抽成】，不是"全营收抽成"—— 只有经 CRS 渠道成交的部分被抽。
// 公开面未披露渠道占比（20-F 只披露区间，未披露分渠道）⇒ 采用【教学假设 30%】：
//   有效费率 = 8% × 30% = 2.4%  ⇒ 管理费 5% + CRS 2.4% = 7.4%（决策端"排序不变"证据的那个 7.4%）
// ⚠️ 置信度【低】：30% 是假设值，非官方披露。改它会直接改学生看到的现金流 ⇒ 须走《学生感知变化清单》。
export const CRS_渠道占比 = {
  值: 0.30,
  置信度: '低',
  来源: '教学假设（20-F 未披露 CRS 分渠道占比）· 用于把 8% 名义费率折算成有效费率',
}
// 官方年度封顶（旧版官方原文）：CRS 以门店总营收 3.5% 封顶 ⇒ 有效费率【不得超过】它。
// 写成守卫而非第二份公式：若有人把渠道占比抬到 > 43.75%，此处先撞上限（而不是静默超收）。
export const CRS_官方封顶 = { 值: 0.035, 来源: '旧版官方加盟站 cc01.html（年度 CRS 以门店总营收 3.5% 封顶）' }

const 费率 = (品牌名) => FRANCHISE_MODEL[品牌名] || null

// 未接入时的【缺项清单】（如实说缺什么，不笼统写"暂不支持"）
export function 缺项(品牌名) {
  const t = 费率(品牌名)
  if (!t) return ['品牌经济条款（管理费 / CRS / 保证金 / 造价）']
  const 缺 = []
  if (!t.管理费?.费率?.值) 缺.push('管理费率')
  if (!t.中央预订系统_CRS?.费率?.值) 缺.push('CRS 费率')
  if (!t.保证金?.值) 缺.push('保证金')
  return 缺.length ? 缺 : ['（费率齐全，未在接入名单）']
}

// 接入状态（界面标注"已实收 / 待补"用；纯查表，不参与计算）
export function franchiseFeeStatus(品牌名) {
  const 名称 = typeof 品牌名 === 'string' ? 品牌名 : (品牌名 && 品牌名.name) || null
  const 接入 = !!名称 && 已接入品牌.includes(名称)
  return {
    品牌: 名称,
    接入,
    原因: 接入 ? '费率来源完整（D53-a 接入名单）' : (名称 ? `缺 ${缺项(名称).join('、')} ⇒ 待补（不编造）` : '未选品牌'),
  }
}

// ── 引擎计费（唯一计算点）────────────────────────────────────
// 传入 brand（对象或品牌名）与本周营收 revenue ⇒ 返回 null（未接入）或费用结构。
// ★ 返回 null 而不是 0 值对象：这样调用方必须显式处理"未接入"，且结算输出能保持逐字节不变。
export function franchiseFees(brand, revenue) {
  const 名称 = typeof brand === 'string' ? brand : (brand && brand.name) || null
  const st = franchiseFeeStatus(名称)
  if (!st.接入) return null
  const 额 = Number(revenue)
  if (!Number.isFinite(额) || 额 <= 0) return null   // 无营收 ⇒ 按营收抽成即为 0 ⇒ 视同未产生费用

  const t = 费率(名称)
  const 管理费率 = t.管理费.费率.值
  const CRS名义率 = t.中央预订系统_CRS.费率.值

  // 有效费率 = 名义 × 渠道占比，但不得超过官方封顶（封顶按【本单】营收同比例折算，周=年 线性等价）
  const CRS有效率 = Math.min(CRS名义率 * CRS_渠道占比.值, CRS_官方封顶.值)
  const 管理费 = Math.round(额 * 管理费率)
  const CRS = Math.round(额 * CRS有效率)
  const 合计 = 管理费 + CRS

  return {
    接入: true,
    品牌: 名称,
    管理费,
    CRS,
    合计,
    占营收比: 合计 / 额,
    费率: { 管理费: 管理费率, CRS名义: CRS名义率, CRS有效: CRS有效率, 合计: 管理费率 + CRS有效率 },
    封顶是否触发: CRS名义率 * CRS_渠道占比.值 > CRS_官方封顶.值,
    // 三件套随行（界面 hover 可追溯；来源 = franchiseModel 的对应条目）
    依据: [
      { 科目: '加盟管理费', 金额: 管理费, 口径: `本周营收 × ${(管理费率 * 100).toFixed(1)}%（加盟资料：月营收 × 费率）`, 来源: t.管理费.费率.来源, 置信度: t.管理费.费率.置信度 },
      { 科目: '加盟CRS', 金额: CRS, 口径: `本周营收 × ${(CRS有效率 * 100).toFixed(1)}%（名义 ${(CRS名义率 * 100).toFixed(1)}% × CRS 渠道占比 ${(CRS_渠道占比.值 * 100).toFixed(0)}%，封顶 ${(CRS_官方封顶.值 * 100).toFixed(1)}%）`, 来源: t.中央预订系统_CRS.费率.来源, 置信度: CRS_渠道占比.置信度 },
    ],
  }
}

// ── 界面用：费用清单（哪几项【已实收】、哪几项【待接入】）──────────────
// 「不许让学生以为全是真金」——已实收的标"本周已扣"，未接入的标"待补/认领页列示"。
export function 费用清单(品牌名) {
  const 名称 = typeof 品牌名 === 'string' ? 品牌名 : (品牌名 && 品牌名.name) || null
  const t = 费率(名称)
  const st = franchiseFeeStatus(名称)
  const 已 = (科目, 费率文案, 来源, 置信度) => ({ 科目, 状态: '已实收', 费率: 费率文案, 来源, 置信度 })
  const 待 = (科目, 说明) => ({ 科目, 状态: '待接入', 费率: null, 说明 })

  if (st.接入) {
    const CRS有效率 = Math.min(t.中央预订系统_CRS.费率.值 * CRS_渠道占比.值, CRS_官方封顶.值)
    return [
      已('加盟管理费', `营收 × ${(t.管理费.费率.值 * 100).toFixed(1)}%`, t.管理费.费率.来源, t.管理费.费率.置信度),
      已('加盟CRS', `营收 × ${(CRS有效率 * 100).toFixed(1)}%（名义 ${(t.中央预订系统_CRS.费率.值 * 100).toFixed(1)}% × 渠道占比 ${(CRS_渠道占比.值 * 100).toFixed(0)}%）`, t.中央预订系统_CRS.费率.来源, CRS_渠道占比.置信度),
      待('加盟费（一次性）', '本轮不进资金流（D53 分步：先月度费率）· 认领页报价单已按投资侧列示'),
      待('保证金（一次性·期末可退）', '引擎暂无"期末退还"钩子 ⇒ 硬接会变假账（已列待决策队列）'),
      待('筹备费 / PMS（一次性）', '认领页报价单已列示；进资金流待队列拍板'),
      { 科目: '单房造价 / capex', 状态: '不接（D53-c）', 费率: null, 说明: 'IC 是「运营启动资金」，与"开店总投资"是两个口径 ⇒ 另立概念、后续批次' },
    ]
  }
  return [
    { 科目: '加盟两费（管理费 + CRS）', 状态: '待补', 费率: null, 说明: `${st.原因} —— 不给该品牌计费（不拿别家费率冒充）` },
  ]
}
