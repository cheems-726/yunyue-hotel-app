// ── 可配置（一处可调）──────────────────────────────────────────────
const 默认配置 = { 装修系数, 附加项, 品质系数 }
const 运行时 = { 当前: 默认配置 }

export function 投资档位配置() { return { ...运行时.当前, 口径, 是否已改动: 运行时.当前 !== 默认配置 } }

/** 一处可调的入口：老师给数后只改这里（校验形状，坏配置直接拒绝，不许半套生效） */
export function 设置投资档位配置(新配置) {
  if (!新配置 || typeof 新配置 !== 'object') return { 成功: false, 原因: '配置必须是对象' }
  const { 装修系数: a, 附加项: b, 品质系数: c } = 新配置
  if (!a || 档位名.some(k => !Number.isFinite(a[k]) || a[k] <= 0)) return { 成功: false, 原因: '装修系数 需为 {低,中,高} 正数' }
  if (!Array.isArray(b) || b.length === 0) return { 成功: false, 原因: '附加项 需为非空数组' }
  for (const it of b) {
    if (!it || !it.key || !it.比例 || 档位名.some(k => !Number.isFinite(it.比例[k]) || it.比例[k] < 0)) {
      return { 成功: false, 原因: `附加项「${it && it.key}」的 比例 需为 {低,中,高} 非负数` }
    }
  }
  if (!c || 档位名.some(k => !Number.isFinite(c[k]))) return { 成功: false, 原因: '品质系数 需为 {低,中,高} 数值' }
  运行时.当前 = 新配置
  return { 成功: true, 配置: 投资档位配置() }
}
export function 重置投资档位配置() { 运行时.当前 = 默认配置; return 投资档位配置() }

export const 默认选择 = { 装修: '中', 软装: '中', IT: '中', 布草: '中', 开办费: '中' }

/**
 * 投资测算（纯函数）
 * @param {{brand:{name:string,standard:string}, 选择?:Record<string,string>}} p
 * @returns {{房量:number, 单房造价:number|null, 档选择:object, 明细:Array, 合计:number|null,
 *            品质分:number, 口径:object, 待补:string[]}}
 */
export function 投资测算({ brand, 选择 } = {}) {
  const 房量 = parseRooms(brand?.standard)
  const t = brand?.name ? FRANCHISE_MODEL[brand.name] : null
  const 单房造价 = t?.单房造价?.新建?.值 ?? null
  const cfg = 运行时.当前
  const 档选择 = { ...默认选择, ...(选择 || {}) }

  // 装修：房量 × 单房造价 × 系数
  const 装修系数v = cfg.装修系数[档选择.装修] ?? cfg.装修系数.中
  const 装修额 = 单房造价 ? Math.round(房量 * 单房造价 * 装修系数v) : null
  const 明细 = [{ key: '装修', 档: 档选择.装修, 金额: 装修额, 说明: `房量 ${房量} × 单房造价 ${单房造价 ?? '待补'} × 系数 ${装修系数v}` }]
  for (const it of cfg.附加项) {
    const 比例 = it.比例[档选择[it.key]] ?? it.比例.中
    const 金额 = (装修额 != null && Number.isFinite(比例)) ? Math.round(装修额 * 比例) : null
    明细.push({ key: it.key, 档: 档选择[it.key], 金额, 说明: `${it.说明}：装修额 × ${比例}` })
  }
  const 全部有值 = 明细.every(x => x.金额 != null)
  const 合计 = 全部有值 ? 明细.reduce((s, x) => s + x.金额, 0) : null
  const 品质分 = Object.entries(档选择).reduce((s, [k, v]) => s + (cfg.品质系数[v] ?? 0), 0) / Object.keys(档选择).length

  return {
    房量, 单房造价, 档选择, 明细, 合计,
    品质分: Math.round(品质分 * 10) / 10,
    口径,
    待补: 单房造价 ? [] : [`${brand?.name || '该品牌'} 的单房造价（无来源 ⇒ 总投资与各档金额都无法算）`],
  }
}

