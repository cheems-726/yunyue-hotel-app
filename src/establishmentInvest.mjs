//
// ── 背景（为什么之前"悬置"）──────────────────────────────────────
//   W3-3（装修档/软装/IT/布草/开办费）一直**悬置**：等老师给金额档位。
//   §16.2-B5 的铺满策略：**用可配置默认档位先填上**（功能完整可用），每档显式标「待老师确认」。
//
// ── 关键设计（★ 不编造数据）─────────────────────────────────────
//   ① **锚在已有来源上**：装修档的"中档"直接取**该品牌的单房造价**
//      （`franchiseModel.单房造价.新建.值` —— 桔子 10.8 万/全季 10.98 万 等都是**官方现行 API** 值）。
//      低/高档 = 中档 × 系数 ⇒ 全套数字都能追到那个**已入库的官方值**，不是凭空写的。
//   ② 其余四项（软装/IT/布草/开办费）官方**无独立来源** ⇒ 用**占装修的比例系数**表达
//      （系数本身是**教学默认档位**，标 `待老师确认: true` + 置信度"低"）。
//   ③ **一处可调**：老师给了真实档位 ⇒ 只改 `投资档位配置`（或调 `设置投资档位配置()`），**不动代码**。
//
// ── 边界（不越界）────────────────────────────────────────────────
//   ★ 纯计算 + 配置：**不被 settlement.js 引用**（守门会断言）⇒ 不参与结算。
//   ★ 品质联动通过**既有的属性机制**（attrs.js 的伪 id）落地，不在本文件里改属性。
