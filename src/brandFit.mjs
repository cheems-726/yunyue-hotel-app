// V113-1.2 · 品牌互斥（在已选区位/已选物业上"装不装得下"）
//
// ── 两种"装不下"（判据 §4-1.2：同一区位下**存在**装不下的品牌组合，要能举证）─────────
//   ① **预算装不下**：该品牌的**最低可行投资**（全低档 + 加盟一次性）> 筹建预算
//   ② **房量装不下**：学生测算的可排房量 < 品牌方要求的最少房量（或落在要求的区间外）
//   ③ 第三种状态是**无法核算**（缺单房造价 / 费率未接入）—— **不许当成"装得下"，也不许当成"装不下"**
//
// ── 边界 ─────────────────────────────────────────────────────────────
//   · 只读：预算来自 `startupBudget.筹建账`（单源）、门槛来自 `propertyQuote.brandTerms`（单源）
//   · 不改任何结算/引擎；只在选品牌与认领两步做"能不能"的判断
import { 筹建账 } from './startupBudget.mjs'
import { brandTerms } from './propertyQuote.mjs'

const 全低 = { 装修: '低', 软装: '低', IT: '低', 布草: '低', 开办费: '低' }

/**
 * 品牌级可行性（不涉及具体物业 → 用品牌标准房量算最低投资）
 * @returns {{状态:'可行'|'超预算'|'无法核算', 最低投资:number|null, 预算:number, 缺口:number, 原因:string}}
 */
export function 品牌可行性({ name, standard } = {}) {
  const 账 = 筹建账({ brand: { name, standard }, 选择: 全低 })
  if (账.合计 == null) {
    const 缺造价 = 账.五项 == null
    return {
      状态: '无法核算', 最低投资: null, 预算: 账.预算, 缺口: 0,
      原因: 缺造价 ? '缺单房造价 ⇒ 投资无法估算' : '加盟费率未接入（加盟费/保证金无来源）⇒ 成本不完整',
    }
  }
  const 缺口 = Math.max(0, 账.合计 - 账.预算)
  return {
    状态: 缺口 > 0 ? '超预算' : '可行',
    最低投资: 账.合计, 预算: 账.预算, 缺口,
    原因: 缺口 > 0
      ? `最低可行投资 ${账.合计} 元 > 预算 ${账.预算} 元（差 ${缺口} 元）—— 已降到最低档仍装不下`
      : `最低可行投资 ${账.合计} 元 ≤ 预算 ${账.预算} 元`,
  }
}

/**
 * 物业级房量判断（认领页用：学生测算的可排房量 vs 品牌方门槛）
 * @param {{name:string}} brand
 * @param {number|null} 测算房量 学生用测算器算出的房量
 * @returns {{装得下:boolean|null, 原因:string, 要求:object|null}}
 */
export function 房量装得下(brand, 测算房量) {
  const t = brandTerms(brand && brand.name)
  const 门槛 = t && t.物业门槛 ? t.物业门槛 : null
  const 最少 = 门槛 && 门槛.最少房量 ? 门槛.最少房量.值 : null
  const 区间 = 门槛 && 门槛.房量区间 ? 门槛.房量区间.值 : null
  if (!Number.isFinite(测算房量)) return { 装得下: null, 原因: '还没算房量（先在测算器里填参数）', 要求: null }
  if (Number.isFinite(最少) && 测算房量 < 最少) {
    return { 装得下: false, 原因: `你测算 ${测算房量} 间 < 品牌最少 ${最少} 间 ⇒ 这家物业装不下「${brand && brand.name}」`, 要求: { 最少房量: 最少 } }
  }
  if (Array.isArray(区间) && (测算房量 < 区间[0] || 测算房量 > 区间[1])) {
    return { 装得下: false, 原因: `你测算 ${测算房量} 间不在品牌要求区间 ${区间[0]}–${区间[1]} 间内`, 要求: { 房量区间: 区间 } }
  }
  if (!Number.isFinite(最少) && !Array.isArray(区间)) {
    return { 装得下: null, 原因: '该品牌未接入房量门槛数据 ⇒ 无法判断（不猜）', 要求: null }
  }
  return { 装得下: true, 原因: `你测算 ${测算房量} 间满足品牌房量要求`, 要求: { 最少房量: 最少, 房量区间: 区间 } }
}
