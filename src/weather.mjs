//   天气影响的是【客流】（到店意愿），不是房价也不是成本 ⇒ 只进 settle 的需求链（乘在 demandStrength 上）。
//   影响幅度刻意做得"看得见但不致命"：暴雨 −20% 客流 ≈ 出租率掉几个百分点，教学生"不可控因素也要会扛"。

// 4 周循环表（12 教学周 ⇒ 正好 3 轮）：晴 / 阴 / 雨 / 暴雨
export const WEATHER_TABLE_CYCLE = [
  { 名: '晴', 图标: 'weather.sunny', 客流: 1.00, 说明: '天气晴好，客流正常' },
  { 名: '阴', 图标: 'weather.cloudy', 客流: 0.96, 说明: '阴天，客流出游意愿略降' },
  { 名: '雨', 图标: 'event.rain', 客流: 0.90, 说明: '下雨，客流明显减少' },
  { 名: '暴雨', 图标: 'weather.storm', 客流: 0.80, 说明: '暴雨，出行受限，客流大跌' },
]

// 按教学周取天气（week 从 1 起；越界/非法按第 1 周处理，绝不抛异常）
export function 天气(week, 表 = WEATHER_TABLE_CYCLE) {
  const w = Math.max(1, Math.round(Number(week) || 1))
  const i = (w - 1) % 表.length
  return { ...表[i], 周: w }
}

// 客流系数（给 settle 用；缺表/坏表 ⇒ 1.0，绝不静默改数）
export function 天气客流系数(week, 表 = WEATHER_TABLE_CYCLE) {
  const c = Number(天气(week, 表).客流)
  return Number.isFinite(c) ? c : 1
}

// 周报/面板文案（唯一生成点；避免各处自己拼百分比 —— 改系数时文案自动跟）
export function 天气文案(week, 表 = WEATHER_TABLE_CYCLE) {
  const t = 天气(week, 表)
  const 偏差 = Math.round((t.客流 - 1) * 100)          // 0 / −4 / −10 / −20
  return {
    ...t,
    文案: 偏差 === 0 ? `本周天气：${t.名}（客流无额外折减）` : `本周天气：${t.名} → 客流 ${偏差}%`,
    系数: t.客流,
  }
}
