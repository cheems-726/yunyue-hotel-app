export const 每天上限 = 2

const 空 = (v) => v == null || v === ''

/** FNV-1a（与 decisionLogIntegrity 同族；此处独立小实现，避免生成器引入引擎依赖） */
function 哈希(s) {
  let h = 2166136261
  const t = String(s)
  for (let i = 0; i < t.length; i++) { h ^= t.charCodeAt(i); h = Math.imul(h, 16777619) }
  return h >>> 0
}
const 取一 = (arr, seed) => arr[哈希(seed) % arr.length]

