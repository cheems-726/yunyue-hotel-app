/** 没有支配选项（不存在"样样不差且至少一项更好"的选项）⇒ 无最优解 */
export function 无最优解(选项) {
  const 支 = (a, b) => a.成本友好 >= b.成本友好 && a.体验 >= b.体验 && a.关系 >= b.关系
    && (a.成本友好 > b.成本友好 || a.体验 > b.体验 || a.关系 > b.关系)
  for (const a of 选项) for (const b of 选项) if (a !== b && 支(a.维度, b.维度)) return false
  return true
}

/**
 * 生成某天 1–2 个委托（纯函数 · 确定性）
 * @param {object} p
 * @param {string} p.种子  跑测种子（同种子同组同天 ⇒ 同委托）
 * @param {string} p.组    组键
 * @param {number} p.天    第几天（1-based）
 * @param {number} p.待处理差评
 * @param {string} p.天气
 * @param {string} p.入住压力  'peak' / 'high' 等
 * @param {string} p.竞品动作
 * @param {object|null} p.注入事件  当周注入事件（含 来源事件）
 * @param {number} p.上限  仅用于 RV（默认 每天上限=2）
 */
export function 生成当日委托({
  种子 = '', 组 = 'g1', 天 = 1, 待处理差评 = 0, 天气 = '晴', 入住压力 = '', 竞品动作 = '',
  注入事件 = null, 上限 = 每天上限,
} = {}) {
  const 信号 = []
  if (Number(待处理差评) > 0) 信号.push('差评处理')
  if (['暴雨', '高温', '寒潮', '大风'].includes(String(天气))) 信号.push('天气应对')
  if (['peak', 'high'].includes(String(入住压力))) 信号.push('高峰排班')
  if (!空(竞品动作)) 信号.push('竞品动作')
  // 客人在店始终可用（没有其它信号时也有事做）
  信号.push('客人在店')

  const 主 = 取一(信号, `${种子}|${组}|${天}|主`)
  const 事件类 = 注入事件 ? (事件相关类[注入事件.来源事件] || '客人在店') : null
  const 序列 = []
  for (const k of [主, 事件类, ...信号]) if (k && !序列.includes(k)) 序列.push(k)
  // 有注入事件 ⇒ 必须"额外 1 个"：若相关类恰好就是主类且没有别的候选，补一个通用类
  if (事件类 && 序列.length < 2) 序列.push(序列.includes('客人在店') ? '天气应对' : '客人在店')
  const 取数 = 事件类 ? Math.min(Math.max(1, Number(上限) || 1), 序列.length) : 1

  return 序列.slice(0, 取数).map((类, i) => {
    const 库 = 委托库[类]
    return {
      id: `${天}|${类}`,
      天: Number(天),
      类,
      标题: 库.标题,
      场景: `第 ${天} 天 · ${库.场景}`,
      选项: 库.选项.map(o => ({ label: o.label, 代价: o.代价, 维度: { ...o.维度 } })),
      需写一句: i === 0 && Number(天) > 0 && Number(天) % 3 === 0,   // 每 3 天至少一次
      只记录: true,                                                   // 第一版：引擎不读（零变化红线）
    }
  })
}
