// ★ V97（2026-10-09 · 用户点名）：统一「返回 / 上一页」导航栈 —— **纯逻辑，无 DOM/React 依赖** ⇒ 可单测
//   设计：任何「进入」= 入栈；「返回」= **弹栈回到上一处**（不是固定跳回某一页）。
//   ★ 既有约定（App.jsx:1823-1828「决策面板不注册历史层」）**不被推翻**：本模块只管栈语义，
//     面板要不要吃手势由接线处决定（V97 折中：**按钮生效 · 手势/返回键不生效** ⇒ 保住『不误退出』初衷）。

export function 创建导航栈(初始) {
  const 栈 = [初始]
  return {
    当前: () => 栈[栈.length - 1],
    纵深: () => 栈.length - 1,
    可以返回: () => 栈.length > 1,
    进入(处) { if (处 && 处 !== 栈[栈.length - 1]) 栈.push(处); return 栈[栈.length - 1] },
    返回() { if (栈.length > 1) 栈.pop(); return 栈[栈.length - 1] },
    重置(处) { 栈.length = 0; 栈.push(处); return 处 },
    快照: () => [...栈],
  }
}

// popstate / 「上一页」按钮的统一处理器（**纯函数** ⇒ 断言 ④ 可直接派发验证）
//   返回 true = 消费了这次返回（栈非空）；false = 无处可退（调用方应放行给浏览器）
export function 造返回处理器(栈, 应用) {
  return () => { if (!栈.可以返回()) return false; 应用(栈.返回()); return true }
}

