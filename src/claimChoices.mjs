/** 已做取舍的摘要（后续步骤展示"你放弃了什么"） */
export function 取舍摘要(取舍, 步骤们) {
  const m = 取舍 && typeof 取舍 === 'object' ? 取舍 : {}
  const keys = Array.isArray(步骤们) ? 步骤们 : Object.keys(认领取舍项)
  return keys.filter(k => m[k]).map(k => `${认领取舍项[k] ? 认领取舍项[k].标题.split('：')[0] : k}：${m[k]}`)
}

/** 某步是否可进入下一步（选了且需要时理由合格） */
export function 本步可继续(key, 取舍, 理由, 理由合格Fn) {
  const 项 = 认领取舍项[key]
  if (!项) return true
  if (!取舍 || !取舍[key]) return false
  if (项.需理由) return !!(理由合格Fn && 理由合格Fn(理由 && 理由[key]))
  return true
}
