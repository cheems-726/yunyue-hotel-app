/**
 * 可排房量测算（学生自己算房量用的**算法工具** · V113-0.1）
 *   可排房量 = ⌊建筑面积 × 得房率 ÷ 单房建筑面积⌋
 * 入参非法（≤0 / NaN）⇒ 返回 null（界面显示"参数不合法"，不返回 0 冒充结果）
 */
export function estimateRooms({ areaNum, 得房率, 单房建筑面积 } = {}) {
  const a = Number(areaNum), r = Number(得房率), s = Number(单房建筑面积)
  if (!Number.isFinite(a) || !Number.isFinite(r) || !Number.isFinite(s)) return null
  if (a <= 0 || r <= 0 || r > 1 || s <= 0) return null
  return Math.floor((a * r) / s)
}

// 品牌档次 → 物业档键（供测算默认参数取用 · 与 getPropertyList 同一映射，防两处漂移）
export function getPropertyTier(brandLevel) {
  const lv = String(brandLevel || '')
  if (lv.includes('经济') || lv.includes('国民')) return '经济型'
  if (lv.includes('中高档') || lv.includes('精选')) return '中高档'
  if (lv.includes('高档')) return '高档'
  return '中档'
}

// 品牌档次 → 物业档（与 Claim 既有映射一致：经济/国民→经济型；精选/中高档→中高档；高档→高档；其余→中档）
export function getPropertyList(brandLevel) {
  return PROPERTIES[getPropertyTier(brandLevel)]
}
