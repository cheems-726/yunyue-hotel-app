/** 取某一档的参照（缺档 ⇒ null，不猜） */
export function 参照(档) {
  return 行业参照[档] || null
}

/**
 * 实测值 vs 参照（纯展示）
 * @param {string} 档 经济型/中档/中高档/高档
 * @param {{occ?:number, adr?:number, revpar?:number}} 实测 occ 为比例（0–1）
 * @returns {null | {档, 星级, 项: Array<{名, 实测, 参照, 差, 差率}>}}
 */
export function 对照(档, 实测 = {}) {
  const b = 行业参照[档]
  if (!b) return null
  const 项 = []
  const add = (名, v, 参照值) => {
    if (!Number.isFinite(v) || !Number.isFinite(参照值) || 参照值 === 0) return
    项.push({ 名, 实测: v, 参照: 参照值, 差: v - 参照值, 差率: (v - 参照值) / 参照值 })
  }
  add('OCC', 实测.occ, b.OCC.值)
  add('ADR', 实测.adr, b.ADR.值)
  add('RevPAR', 实测.revpar, b.RevPAR.值)
  return { 档: b.档, 星级: b.星级, 来源: b.OCC.来源, 项 }
}
